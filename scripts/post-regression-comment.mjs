#!/usr/bin/env node
// Renders one or more `savedyouatoken policy check --json` / `compare --json` result files into
// a single pull-request comment, and updates it idempotently across reruns.
//
//   node scripts/post-regression-comment.mjs <result.json...>
//
// This is deliberately a thin renderer over CLI JSON, not a second analysis implementation —
// see design.md's "Build GitHub feedback from versioned JSON output" decision. It never reads a
// prompt file itself and never prints anything from `diff.findings` beyond a rule id, so the
// prompt-free guarantee carries through the whole pipeline into the comment.
//
// Required env: GITHUB_TOKEN, GITHUB_REPOSITORY (owner/repo), GITHUB_EVENT_PATH (for the PR
// number). When posting is impossible — no PR context, no token, or the API rejects the
// request — this falls back to $GITHUB_STEP_SUMMARY and still exits 0: a failed *comment* must
// never mask or replace the `policy check` step's own exit code, which is the real CI gate.
import { appendFileSync, readFileSync } from 'node:fs';

export const MARKER = '<!-- savedyouatoken:regression-report -->';

export function renderMarkdown(results) {
  const lines = [MARKER, '', '## savedyouatoken regression report', ''];
  const sorted = [...results].sort((a, b) => assetId(a).localeCompare(assetId(b)));

  for (const result of sorted) {
    lines.push(...renderAsset(result));
  }

  lines.push(
    '',
    '<sub>Cost-only evidence, not a quality signal — review before trusting a rewrite. ' +
      'Generated by `savedyouatoken policy check` / `compare`.</sub>',
  );
  return lines.join('\n');
}

function assetId(result) {
  return result.target?.id ?? result.workflow?.id ?? 'unknown';
}

function renderAsset(result) {
  const id = assetId(result);
  const badge = outcomeBadge(result);
  const lines = [`### ${badge} \`${id}\``, ''];

  const diff = result.diff;
  if (!diff) {
    lines.push('_No baseline was available for this asset — nothing to compare._', '');
    return lines;
  }
  if (diff.compatibility.status === 'invalid') {
    lines.push(`⚠️ **Cannot compare against the baseline:** ${diff.compatibility.reasons.join(', ')}.`, '');
    return lines;
  }
  if (diff.compatibility.status === 'approximate') {
    lines.push(`_Approximate comparison: ${diff.compatibility.reasons.join(', ')}. Treat the delta as directional._`, '');
  }

  lines.push('| Metric | Baseline | Current | Δ |', '| --- | ---: | ---: | ---: |');
  lines.push(deltaRow('Input tokens', diff.tokens.inputTokens, formatNumber));
  lines.push(deltaRow('Monthly cost', diff.cost.monthlyNow, formatUsd));
  lines.push('');

  if (result.breaches?.length) {
    lines.push('**Policy breaches:**');
    for (const breach of result.breaches) {
      lines.push(`- \`${breach.budget}\`: ${breach.actual} exceeds the limit of ${breach.limit}`);
    }
    lines.push('');
  }

  const changedFindings = (diff.findings ?? []).filter((f) => f.status !== 'unchanged');
  if (changedFindings.length) {
    lines.push('**Finding changes:** ' + changedFindings.map((f) => `${f.status} \`${f.ruleId}\``).join(', '), '');
  }

  const actions = nextActions(result);
  if (actions.length) {
    lines.push('**Next actions:**');
    for (const action of actions) lines.push(`- ${action}`);
    lines.push('');
  }

  return lines;
}

function outcomeBadge(result) {
  if (!('outcome' in result)) return 'ℹ️ compared';
  return { pass: '✅ pass', warn: '⚠️ warn', fail: '❌ fail' }[result.outcome] ?? result.outcome;
}

function nextActions(result) {
  if (result.outcome === 'fail') {
    return [
      'Reduce the prompt back under budget, or if this growth is intentional, refresh the policy: ' +
        '`savedyouatoken policy generate --baseline <path> --out <path>`.',
    ];
  }
  if (result.outcome === 'warn') {
    return ['This is a warning, not a build failure — review the change before it becomes a `fail` budget.'];
  }
  return [];
}

function deltaRow(label, field, format) {
  const sign = field.delta > 0 ? '+' : '';
  return `| ${label} | ${format(field.baseline)} | ${format(field.current)} | ${sign}${format(field.delta)} |`;
}

function formatNumber(n) {
  return Math.round(n).toLocaleString('en-US');
}

// Mirrors packages/core/src/cost.ts's formatUsd exactly (magnitude-scaled precision), so the
// same dollar amount reads identically here and in the CLI's own terminal/--json output. This is
// a deliberate copy, not an import: packages/core ships as TypeScript source with no build step
// of its own, and this script runs under plain `node` with no bundler — see docs/decisions.md.
// Keep this in sync with cost.ts's formatUsd if that ever changes.
function formatUsd(n) {
  const abs = Math.abs(n);
  if (abs === 0) return '$0';
  if (abs < 0.01) return `$${n.toFixed(4)}`;
  if (abs < 1) return `$${n.toFixed(3)}`;
  if (abs < 1000) return `$${n.toFixed(2)}`;
  return `$${Math.round(n).toLocaleString('en-US')}`;
}

/** Finds an existing marker-bearing comment among a PR's comments, for idempotent updates. */
export function findExistingCommentId(comments) {
  const existing = comments.find((comment) => comment.body?.includes(MARKER));
  return existing ? existing.id : null;
}

export async function postOrUpdateComment(body) {
  const token = process.env.GITHUB_TOKEN;
  const repo = process.env.GITHUB_REPOSITORY;
  const eventPath = process.env.GITHUB_EVENT_PATH;
  if (!token || !repo || !eventPath) {
    throw new Error('missing GITHUB_TOKEN, GITHUB_REPOSITORY, or GITHUB_EVENT_PATH — not running in a PR context');
  }
  const event = JSON.parse(readFileSync(eventPath, 'utf8'));
  const prNumber = event.pull_request?.number ?? event.number;
  if (!prNumber) throw new Error('no pull_request number in the triggering event');

  const api = `https://api.github.com/repos/${repo}`;
  const headers = {
    Authorization: `Bearer ${token}`,
    Accept: 'application/vnd.github+json',
    'X-GitHub-Api-Version': '2022-11-28',
  };

  const listResponse = await fetch(`${api}/issues/${prNumber}/comments?per_page=100`, { headers });
  if (!listResponse.ok) throw new Error(`listing comments failed: ${listResponse.status} ${await listResponse.text()}`);
  const comments = await listResponse.json();
  const existingId = findExistingCommentId(comments);

  const writeResponse = existingId
    ? await fetch(`${api}/issues/comments/${existingId}`, {
        method: 'PATCH',
        headers: { ...headers, 'Content-Type': 'application/json' },
        body: JSON.stringify({ body }),
      })
    : await fetch(`${api}/issues/${prNumber}/comments`, {
        method: 'POST',
        headers: { ...headers, 'Content-Type': 'application/json' },
        body: JSON.stringify({ body }),
      });

  if (!writeResponse.ok) throw new Error(`writing the comment failed: ${writeResponse.status} ${await writeResponse.text()}`);
  return existingId ? 'updated' : 'created';
}

export function writeSummaryFallback(body, reason) {
  const summaryPath = process.env.GITHUB_STEP_SUMMARY;
  const note = `> Comment not posted (${reason}); showing the report here instead.\n\n`;
  if (summaryPath) {
    appendFileSync(summaryPath, note + body + '\n');
  } else {
    process.stdout.write(note + body + '\n');
  }
}

async function main() {
  const paths = process.argv.slice(2);
  if (!paths.length) {
    console.error('usage: post-regression-comment.mjs <result.json...>');
    process.exit(2);
  }

  let results;
  try {
    results = paths.map((path) => JSON.parse(readFileSync(path, 'utf8')));
  } catch (err) {
    console.error(`✗ could not read a result file: ${err.message}`);
    process.exit(2);
  }

  const body = renderMarkdown(results);

  try {
    const action = await postOrUpdateComment(body);
    console.log(`✓ ${action} the pull-request comment.`);
  } catch (err) {
    console.warn(`⚠ could not post a pull-request comment (${err.message}); falling back to the job summary.`);
    writeSummaryFallback(body, err.message);
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main();
}
